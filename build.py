#!/usr/bin/env python3
"""Usage:
  python3 build.py            Build standalone ./run_block from src/ modules and src/rules/
  python3 build.py --check    Verify that ./run_block is up to date with src/ (exit 0 if clean, 1 if stale)
  python3 build.py -h|--help  Print this usage and exit 0
"""
from __future__ import annotations

if __doc__ is None:
    raise SystemExit("missing usage documentation")

import ast
import pprint
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SRC_DIR = ROOT / "src"
OUT_FILE = ROOT / "run_block"

MODULE_ORDER = [
    "header.py",
    "config.py",
    "__embedded__",
    "agents.py",
    "safety.py",
    "ui.py",
    "runner.py",
    "tree.py",
    "bundle.py",
    "cli.py",
]

RULE_ORDER = [
    "blocks/bash",
    "blocks/pwsh",
    "core/start",
    "core/secrets",
    "core/plan",
    "core/edit",
    "core/diff-review",
    "core/external",
    "core/end",
    "core/lang",
    "vcs/git",
    "vcs/cvs",
    "release/semver",
    "release/single-file-build",
    "stack/python-cli",
]


def load_embedded_assets() -> str:
    rules_root = SRC_DIR / "rules"
    rule_files = {
        p.relative_to(rules_root).with_suffix("").as_posix(): p
        for p in sorted(rules_root.rglob("*.md"))
    }
    ordered_names = [k for k in RULE_ORDER if k in rule_files] + [
        k for k in sorted(rule_files) if k not in RULE_ORDER
    ]
    rules: dict[str, tuple[str, str]] = {}
    for name in ordered_names:
        raw = rule_files[name].read_text(encoding="utf-8").splitlines()
        desc = name
        body_lines = raw
        if raw and raw[0].startswith("# Description:"):
            desc = raw[0].split(":", 1)[1].strip()
            body_lines = raw[1:]
        rules[name] = (desc, "\n".join(body_lines).strip())

    presets: dict[str, tuple[str, list[str]]] = {}
    for raw_line in (SRC_DIR / "presets.txt").read_text(encoding="utf-8").splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#"):
            continue
        parts = [x.strip() for x in line.split("|")]
        if len(parts) == 3:
            name, desc, items_s = parts
            items = [x.strip() for x in items_s.split(",") if x.strip()]
            presets[name.lower()] = (desc, items)

    lines = [
        "# --- Embedded rules and presets (generated by build.py from src/) ---",
        f"EMBEDDED_RULES: dict[str, tuple[str, str]] = {pprint.pformat(rules, width=100, sort_dicts=False)}",
        "",
        f"EMBEDDED_PRESETS: dict[str, tuple[str, list[str]]] = {pprint.pformat(presets, width=100, sort_dicts=False)}",
        "",
    ]
    return "\n".join(lines)


def assemble_source() -> str:
    chunks: list[str] = []
    for item in MODULE_ORDER:
        if item == "__embedded__":
            chunks.append(load_embedded_assets().rstrip())
        else:
            mod_path = SRC_DIR / item
            chunks.append(mod_path.read_text(encoding="utf-8").rstrip())
    source = "\n\n\n".join(chunks) + "\n"
    ast.parse(source)
    return source


def main(argv: list[str] | None = None) -> int:
    args = list(sys.argv[1:] if argv is None else argv)
    if "-h" in args or "--help" in args:
        sys.stdout.write(__doc__)
        return 0
    expected = assemble_source()
    if "--check" in args:
        if not OUT_FILE.is_file():
            sys.stderr.write("build.py: run_block does not exist\n")
            return 1
        actual = OUT_FILE.read_text(encoding="utf-8")
        if actual != expected:
            sys.stderr.write("build.py: run_block is out of sync with src/ (run 'python3 build.py')\n")
            return 1
        return 0
    if args:
        sys.stderr.write(__doc__)
        return 2
    OUT_FILE.write_text(expected, encoding="utf-8")
    OUT_FILE.chmod(0o755)
    sys.stdout.write(f"build.py: built {OUT_FILE} ({len(expected.splitlines())} lines)\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
